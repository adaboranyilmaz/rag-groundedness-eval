def main() -> None:
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--pilot", action="store_true")
    mode.add_argument("--dry-run", action="store_true")
    mode.add_argument("--offline", action="store_true")
    mode.add_argument("--sync", action="store_true")
    parser.add_argument("--no-mlflow", action="store_true")
    args = parser.parse_args()

    load_dotenv()
    cfg = yaml.safe_load(CONFIG_PATH.read_text(encoding="utf-8"))
    gen_cfg = yaml.safe_load(GENERATION_CONFIG_PATH.read_text(encoding="utf-8"))
    inputs = load_inputs(cfg)
    cache = ResponseCache()
    print(
        f"{len(inputs.traces)} traces; {len(inputs.numeric_golds)} numeric-gold questions; "
        f"{sum(needs_judge(t['parsed']) for t in inputs.traces)} need the judge"
    )
    if args.dry_run:
        dry_run(cfg, inputs, cache)
        return

    judge_mode = "sync" if (args.pilot or args.sync) else ("offline" if args.offline else "batch")
    ledger = None if args.offline else make_ledger(cfg)
    judge = Judge(cfg, cfg["judge"]["model"], judge_mode, cache, ledger)
    traces = select_pilot(inputs, cfg) if args.pilot else inputs.traces
    try:
        records = evaluate(traces, inputs, judge, cfg)
    except BudgetExceeded as e:
        sys.exit(f"STOPPED: {e}\nCompleted calls are cached; nothing is lost.")
    spend = {
        "new_cost_usd_this_run": round(judge.new_cost_usd, 6),
        "judge_results_missing": judge.n_missing,
        "batch_failures": [f for o in judge.batch_outcomes for f in o.failures],
    }
    # Totals from the ledger (read-only in offline mode), so a re-run that spends nothing
    # still records what the phase cost; `new_cost_usd_this_run` is this invocation's.
    ledger_view = ledger if ledger is not None else make_ledger(cfg)
    spend["phase_spent_usd"] = round(ledger_view.phase_spent(), 6)
    spend["project_spent_usd"] = round(ledger_view.state["total_usd"], 6)
    print(f"judge: {spend}")

    if args.pilot:
        write_jsonl(RESULTS_DIR / "eval_pilot_per_trace.jsonl", records)
        (RESULTS_DIR / "eval_pilot_review.md").write_text(
            review_markdown(records, inputs), encoding="utf-8", newline="\n"
        )
        print(f"wrote {len(records)} pilot records and eval_pilot_review.md")
        return

    write_jsonl(RESULTS_DIR / "eval_per_trace.jsonl", records)
    summary = summarise(records, cfg)
    nb, seed = cfg["bootstrap"]["n_resamples"], cfg["bootstrap"]["seed"]
    crosscheck = correctness_crosscheck(records, nb, seed)
    (RESULTS_DIR / "correctness_crosscheck.json").write_text(
        json.dumps(crosscheck, indent=2, ensure_ascii=False), encoding="utf-8", newline="\n"
    )
    main_out = {
        "meta": {
            "updated_utc": datetime.now(UTC).isoformat(timespec="seconds"),
            "single_run": True,
            "judge_mode": judge_mode,
            "judge": judge_meta(judge),
            "config": cfg,
            "n_traces": len(records),
            "n_questions": len({r["financebench_id"] for r in records}),
            "numeric_gold_question_ids": sorted(inputs.numeric_golds),
            "correctness_crosscheck": {
                k: crosscheck[k] for k in ("n", "table_numeric_by_judge", "unit_error_flags")
            }
            | {"binary_kappa": crosscheck["binary_correct"]["kappa"]},
            "spend": spend,
            "environment": {
                "python": platform.python_version(),
                "anthropic": pkg_version("anthropic"),
            },
        },
        **summary,
    }
    (RESULTS_DIR / "eval_main.json").write_text(
        json.dumps(main_out, indent=2, ensure_ascii=False), encoding="utf-8", newline="\n"
    )
    plot_reliability(
        summary["reliability"],
        cfg["traces"]["conditions"],
        cfg["traces"]["models"],
        PLOTS_DIR / "reliability_diagram.png",
    )
    print_summary(summary)
    print("wrote eval_per_trace.jsonl, eval_main.json, correctness_crosscheck.json, plot")
    if not args.no_mlflow:
        versions = {arm_key(r): r["prompt_version"] for r in records}
        log_mlflow(cfg, gen_cfg, summary, judge, versions)


if __name__ == "__main__":
    main()
