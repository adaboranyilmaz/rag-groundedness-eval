"""Evaluate every Phase 4 generation trace on the four Phase 5 metric families: answer
correctness, groundedness, citation quality and abstention (src/evaluation/).

Modes:
  --pilot     a fixed sample (configs/evaluation.yaml `pilot`) judged with standard API calls,
              for review before the judge prompts are frozen
              -> results/metrics/eval_pilot_per_trace.jsonl, eval_pilot_review.md
  --dry-run   cost estimate for the full run; needs the pilot's cached results for output
              lengths and claim rates -> results/metrics/eval_cost_estimate.json
  (default)   every trace; judge calls through the Message Batches API (half price)
              -> results/metrics/eval_per_trace.jsonl   one record per trace
                 results/metrics/eval_main.json          per-arm aggregates with 95% CIs,
                                                         reliability bins, detector agreement
                 results/metrics/correctness_crosscheck.json
                 results/plots/reliability_diagram.png
                 one MLflow run per (condition, model, prompt) arm
  --offline   the default outputs from the response cache only: no API calls. Re-running it
              reproduces eval_per_trace.jsonl byte for byte.
  --sync      the full run with standard API calls instead of batches

Every judge response is cached on disk by request hash (data/cache/llm/), and all spend goes
through the ledger (results/metrics/api_spend.json) under the caps in the config.

Usage:
    uv run python scripts/06_eval_generation.py --pilot
    uv run python scripts/06_eval_generation.py --dry-run
    uv run python scripts/06_eval_generation.py
    uv run python scripts/06_eval_generation.py --offline
"""

