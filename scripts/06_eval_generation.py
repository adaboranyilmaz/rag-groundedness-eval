def dry_run(cfg: dict, inputs: Inputs, cache: ResponseCache) -> None:
    """Expected and worst-case cost of the full run's uncached judge calls. Stage-1 calls
    are known exactly. Stage-2 calls depend on stage 1, so they are estimated: verification
    requests use the answer as a stand-in for its claims, scaled by the pilot's ratio of
    claim text to answer text; correctness calls are assumed for every trace the rule-based
    detector does not mark declined. Input tokens are measured with the token-counting
    endpoint on a sample of each request type; output lengths are the pilot's means."""
    import anthropic

    client = anthropic.Anthropic()
    judge = Judge(cfg, cfg["judge"]["model"], "offline", cache, None, log=lambda s: None)
    pilot_path = RESULTS_DIR / "eval_pilot_per_trace.jsonl"
    if not pilot_path.exists():
        sys.exit("run --pilot first: the estimate uses the pilot's output lengths")
    pilot = [json.loads(x) for x in pilot_path.read_text(encoding="utf-8").splitlines()]

    out_tokens: dict[str, list[int]] = defaultdict(list)
    claim_chars, answer_chars, has_claims, decomposed = 0, 0, 0, 0
    for r in pilot:
        for stage, key in r["judge"].items():
            resp = cache.get(key)
            if resp is not None and resp.output_tokens is not None:
                out_tokens[stage].append(resp.output_tokens)
        g = r["groundedness"]
        if r["abstention"]["judge"] is not None:
            decomposed += 1
            if g is not None and g["claims"]:
                has_claims += 1
                claim_chars += sum(len(c["claim"]) for c in g["claims"])
                answer_chars += len(r["answer"])
    p_claims = has_claims / decomposed
    # A ratio of totals: a mean of per-answer ratios is dominated by terse answers ("62.3"
    # becomes a full-sentence claim, ~10x its length) and overstates long answers' claims.
    ratio = claim_chars / answer_chars

    traces = [t for t in inputs.traces if needs_judge(t["parsed"])]
    not_declined = [t for t in traces if rule_status(t["parsed"]) != "declined"]
    requests = {
        "decompose": [
            judge.request("decompose", decompose_values(t), DECOMPOSE_SCHEMA) for t in traces
        ],
        "verify": [
            judge.request(
                "verify",
                verify_values(t, [{"claim": t["parsed"]["answer"]}]),
                verify_schema([c["label"] for c in t["retrieval"]["chunks"]]),
            )
            for t in traces
        ],
        "correctness": [
            judge.request(
                "correctness",
                correctness_values(t, inputs.gold_rows[t["question"]["financebench_id"]]),
                CORRECTNESS_SCHEMA,
            )
            for t in not_declined
        ],
    }
    extra_chars = {
        "decompose": [0] * len(traces),
        "verify": [(ratio - 1) * len(t["parsed"]["answer"]) for t in traces],
        "correctness": [0] * len(not_declined),
    }
    share = {"decompose": 1.0, "verify": p_claims, "correctness": 1.0}
    price = cfg["budget"]["prices_usd_per_mtok"][judge.model_cfg["model"]]
    disc = cfg["budget"]["batch_discount"]
    rng = random.Random(0)
    stages, total_exp, total_worst = {}, 0.0, 0.0
    for stage, reqs in requests.items():
        sample = rng.sample(reqs, min(10, len(reqs)))
        counted = [
            client.messages.count_tokens(
                model=r.model,
                system=r.system,
                messages=[{"role": "user", "content": r.user}],
                output_config=r.params["output_config"],
            ).input_tokens
            for r in sample
        ]
        tpc = sum(counted) / sum(len(r.system) + len(r.user) for r in sample)
        todo = [
            (r, x)
            for r, x in zip(reqs, extra_chars[stage], strict=True)
            if not cache.has(r.cache_key)
        ]
        n_calls = len(todo) * share[stage]
        in_tok = sum((len(r.system) + len(r.user) + x) * tpc for r, x in todo) * share[stage]
        out_mean = statistics.fmean(out_tokens[stage])
        exp = (in_tok * price["input"] + n_calls * out_mean * price["output"]) / 1e6 * disc
        worst = (
            (in_tok * price["input"] + n_calls * judge.max_tokens[stage] * price["output"])
            / 1e6
            * disc
        )
        stages[stage] = {
            "calls_est": round(n_calls),
            "input_tokens_est": round(in_tok),
            "tokens_per_char_measured": round(tpc, 4),
            "output_tokens_mean_pilot": round(out_mean, 1),
            "n_pilot_outputs": len(out_tokens[stage]),
            "expected_usd": round(exp, 4),
            "worst_case_usd": round(worst, 4),
        }
        total_exp += exp
        total_worst += worst
    ledger = make_ledger(cfg)
    estimate = {
        "meta": {
            "run_utc": datetime.now(UTC).isoformat(timespec="seconds"),
            "estimate": True,
            "batch_discount": disc,
            "prices_as_of": cfg["budget"]["prices_as_of"],
            "n_traces_needing_judge": len(traces),
            "n_not_declined_by_rule": len(not_declined),
            "pilot_share_with_claims": round(p_claims, 4),
            "pilot_claims_to_answer_chars": round(ratio, 3),
            "n_pilot_traces": len(pilot),
        },
        "stages": stages,
        "total_expected_usd": round(total_exp, 4),
        "total_worst_case_usd": round(total_worst, 4),
        "phase_spent_usd": round(ledger.phase_spent(), 4),
        "project_spent_usd": round(ledger.state["total_usd"], 4),
        "caps": {"project_usd": ledger.project_cap_usd, "phase_usd": ledger.phase_cap_usd},
    }
    out = RESULTS_DIR / "eval_cost_estimate.json"
    out.write_text(json.dumps(estimate, indent=2), encoding="utf-8", newline="\n")
    print(json.dumps(estimate, indent=2))
    print(f"wrote {out}")


