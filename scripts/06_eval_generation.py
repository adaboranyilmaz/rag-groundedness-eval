def arm_key(r: dict) -> str:
    return f"{r['condition']}__{r['model_key']}__{r['prompt_id']}"


def summarise(records: list[dict], cfg: dict) -> dict:
    groups: dict[str, list[dict]] = defaultdict(list)
    pooled: dict[str, list[dict]] = defaultdict(list)
    for r in records:
        groups[arm_key(r)].append(r)
        pooled[f"{r['condition']}__{r['model_key']}"].append(r)
    n_bins = cfg["reliability"]["n_bins"]
    reliability = {}
    for key, rs in sorted(pooled.items()):
        pairs = calibration_pairs(rs)
        reliability[key] = {k: calibration(v, n_bins) for k, v in pairs.items()}
    nb, seed = cfg["bootstrap"]["n_resamples"], cfg["bootstrap"]["seed"]
    return {
        "arms": {k: aggregate(v, cfg) for k, v in sorted(groups.items())},
        "by_condition_model": {k: aggregate(v, cfg) for k, v in sorted(pooled.items())},
        "reliability": reliability,
        "abstention_detector_agreement": detector_agreement(records, nb, seed),
    }


def print_summary(summary: dict) -> None:
    print(
        f"\n{'arm':52s} {'n':>4s} {'acc':>6s} {'acc|ans':>7s} {'ground':>7s} {'full':>6s}"
        f" {'cit.p':>6s} {'decl':>5s}"
    )
    for key, a in summary["arms"].items():
        c, g, cit = a["correctness"], a["groundedness"], a["citations"]
        cells = [
            c["accuracy_all"]["rate"],
            c["accuracy_answered"]["rate"],
            g["mean_groundedness"]["mean"],
            g["fully_grounded"]["rate"],
            cit["citation_precision"]["mean"],
        ]
        widths = (6, 7, 7, 6, 6)
        decl = a["abstention"]["status_counts"]["declined"] / a["n"]
        row = " ".join(f"{_fmt(v):>{w}s}" for v, w in zip(cells, widths, strict=True))
        print(f"{key:52s} {a['n']:4d} {row} {decl:5.2f}")


def log_mlflow(
    cfg: dict, gen_cfg: dict, summary: dict, judge: Judge, prompt_versions: dict[str, int]
) -> None:
    import mlflow

    from src.tracking.mlflow_utils import init_tracking

    init_tracking()
    rc = gen_cfg["retrieval"]
    jm = judge_meta(judge)
    for key, a in summary["arms"].items():
        cond, model, prompt = key.split("__")
        with mlflow.start_run(run_name=f"eval__{key}"):
            mlflow.set_tags({"phase": PHASE, "single_run": "True"})
            mlflow.log_params(
                {
                    "context_condition": cond,
                    "model_key": model,
                    "prompt_id": prompt,
                    "prompt_version": prompt_versions[key],
                    "chunking": rc["chunking"],
                    "embedder": rc["embedding"],
                    "retriever": rc["method"],
                    "k": rc["k"],
                    "judge_model": jm["model"],
                    **{f"judge_prompt_{p}": v["id"] for p, v in jm["prompts"].items()},
                    **{
                        f"judge_prompt_{p}_sha256": v["file_sha256"]
                        for p, v in jm["prompts"].items()
                    },
                    "numeric_rel_tol": cfg["correctness"]["rel_tol"],
                    "n_traces": a["n"],
                }
            )
            c, g, cit, cal = a["correctness"], a["groundedness"], a["citations"], a["calibration"]
            metrics = {
                "accuracy_all": c["accuracy_all"]["rate"],
                "accuracy_answered": c["accuracy_answered"]["rate"],
                "unit_error_rate_answered": c["unit_error_rate_answered"],
                "mean_groundedness": g["mean_groundedness"]["mean"],
                "fully_grounded_rate": g["fully_grounded"]["rate"],
                "any_contradicted_rate": g["any_contradicted"]["rate"],
                "claim_supported_rate": g["claim_level"]["supported_rate"],
                "citation_precision": cit["citation_precision"]["mean"],
                "citation_recall": cit["citation_recall"]["mean"],
                "gold_cited_rate": cit["gold_cited"]["rate"],
                "quote_faithful_rate": cit["quotes"]["faithful_rate"],
                "ece_correct": cal["correct"]["ece"],
                "ece_fully_grounded": cal["fully_grounded"]["ece"],
                "declined_rate": a["abstention"]["status_counts"]["declined"] / a["n"],
                "judge_errors": sum(a["judge_errors"].values()),
            }
            for group, v in a["abstention"]["by_answerability"].items():
                metrics[f"declined_rate_{group}"] = v["declined"]["rate"]
            mlflow.log_metrics({k: float(v) for k, v in metrics.items() if v is not None})
            mlflow.log_artifact(str(CONFIG_PATH), artifact_path="config")
            for p in jm["prompts"].values():
                mlflow.log_artifact(f"prompts/judge/{p['id']}.md", artifact_path="judge_prompts")


