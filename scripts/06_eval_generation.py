def select_pilot(inputs: Inputs, cfg: dict) -> list[dict]:
    p = cfg["pilot"]
    fids = pilot_questions(
        inputs.traces, p["n_questions_in_corpus"], p["n_questions_out_of_corpus"], p["seed"]
    )
    return pilot_sample(inputs.traces, fids, p["traces_per_cell"], p["seed"])


def evaluate(traces: list[dict], inputs: Inputs, judge: Judge, cfg: dict) -> list[dict]:
    judged = judge_traces(traces, inputs, judge)
    c = cfg["correctness"]
    tols = tuple(c["sensitivity_rel_tols"])
    records = [evaluate_trace(t, inputs, judged[t["trace_id"]], c["rel_tol"], tols) for t in traces]
    return sorted(records, key=lambda r: r["trace_id"])


def write_jsonl(path: Path, records: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [json.dumps(r, ensure_ascii=False, sort_keys=True) for r in records]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def judge_meta(judge: Judge) -> dict:
    return {
        "model": judge.model_cfg["model"],
        "settings": judge.model_cfg,
        "prompts": {
            purpose: {"id": p.id, "version": p.version, "file_sha256": p.file_sha256}
            for purpose, p in judge.prompts.items()
        },
        "max_tokens": judge.max_tokens,
    }


