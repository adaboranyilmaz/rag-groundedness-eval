def _fmt(x) -> str:
    return "n/a" if x is None else (f"{x:.2f}" if isinstance(x, float) else str(x))


def review_markdown(records: list[dict], inputs: Inputs) -> str:
    out = [
        "# Judge pilot review",
        "",
        "Pilot sample only, not results: judge outputs for review before the judge prompts",
        "are frozen. Generated by `scripts/06_eval_generation.py --pilot`.",
        "",
    ]
    for r in records:
        gold = inputs.gold_rows[r["financebench_id"]]
        ab, co, gr, ci = r["abstention"], r["correctness"], r["groundedness"], r["citations"]
        out += [
            f"## {r['trace_id']}",
            "",
            f"- **Question:** {gold['question']}",
            f"- **Gold answer:** {gold['answer']}",
            f"- **Answer:** {r['answer']}",
            f"- **Abstention:** {ab['status']} (from {ab['source']}); rule `{ab['rule']}`, "
            f"judge `{ab['judge']}`; answerability `{r['answerability']}`",
        ]
        line = f"- **Correctness:** `{co['label']}` (grader: {co['grader']})"
        if co["numeric"] and co["numeric"]["primary"]:
            p = co["numeric"]["primary"]
            line += f"; numeric figure `{p['figure']}` -> {p['label']}"
        if co["judge"]:
            line += f"; judge `{co['judge']['grade']}` (unit error {co['judge']['unit_error']}): "
            line += co["judge"]["reason"]
        out.append(line)
        if gr is not None:
            out.append(
                f"- **Groundedness:** {_fmt(gr['groundedness'])} over "
                f"{gr['n_document_claims']} document claims ({gr['n_context_claims']} context, "
                f"{gr['n_general_claims']} general)"
            )
            if gr["claims"]:
                out += [
                    "",
                    "| # | kind | verdict | support | claim | reason |",
                    "|---|---|---|---|---|---|",
                ]
                for i, c in enumerate(gr["claims"], 1):
                    cells = [
                        str(i),
                        c["kind"],
                        c["verdict"],
                        ",".join(c["supporting_excerpts"]),
                        c["claim"].replace("|", "/"),
                        c["reason"].replace("|", "/"),
                    ]
                    out.append("| " + " | ".join(cells) + " |")
                out.append("")
        out.append(
            f"- **Citations:** cited {ci['cited']}, evidence {ci['evidence_labels']}, "
            f"precision {_fmt(ci.get('citation_precision'))}, recall "
            f"{_fmt(ci.get('citation_recall'))}, gold cited {_fmt(ci['gold_cited'])}"
            + (f", quotes {ci['quotes']['statuses']}" if ci["quotes"] else "")
        )
        if r["judge_errors"]:
            out.append(f"- **Judge errors:** {r['judge_errors']}")
        out.append("")
    return "\n".join(out)


